// Build-only illustrations: same generators as the editor, fixed example inks.
// MuPDF is already a root dependency. No browser, live inventory or service needed.
import {mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import mupdf from 'mupdf';
import {families,defaults,generate,fitPaths,loadLimits,usesInkSequence,physicalOptions} from '../patterns/web/generators.js';
import {isComplex} from '../patterns/web/complex.js';

const out=resolve(process.argv[2]||new URL('../build/pattern-thumbnails',import.meta.url).pathname);
await mkdir(out,{recursive:true});await loadLimits();
const colors=['#222222','#008080','#c84253','#245bd6','#a32c99','#a57b00'];
const media={sheet_size_mm:[431.8,279.4],printable_rect_mm:[15,15,401.8,249.4],content_inset_mm:1};
const manifest={},assets=[],width=720,height=460,penWidthMm=.6;
for(const family of families){
 const params=defaults(family.id),count=usesInkSequence(family.id)?colors.length:family.id==='newton'?params.roots:family.roles.length;
 const inks=Array.from({length:count},(_,i)=>({id:String(i),color_srgb:colors[i%colors.length],width_mm:penWidthMm}));
 const recipe={family:family.id,params,media,inks,roles:inks.map(i=>({ink_id:i.id})),size:.96,rotation:0};
 const options={inkCount:count,...physicalOptions(recipe),...(isComplex(family.id)?{resolution:280}:{})};
 if(family.id==='julia')params.detail=280;
 const geometry=generate(family.id,params,()=>{},options),fitted=fitPaths(geometry,recipe);
 if(!fitted.paths.length)throw Error('Empty thumbnail: '+family.id);
 // Match the editor's role paint order, round caps/joins and physical fitting.
 const [pw,ph]=media.sheet_size_mm,scale=Math.min((width-24)/pw,(height-24)/ph);
 const transform=[scale,0,0,scale,(width-pw*scale)/2,(height-ph*scale)/2];
 const pixmap=new mupdf.Pixmap(mupdf.ColorSpace.DeviceRGB,[0,0,width,height],false);pixmap.clear(255);
 const device=new mupdf.DrawDevice(mupdf.Matrix.identity,pixmap);
 const stroke=new mupdf.StrokeState({lineWidth:penWidthMm,lineCap:'Round',lineJoin:'Round',miterLimit:10});
 for(const [role,ink] of inks.entries()){
  const path=new mupdf.Path();
  for(const p of fitted.paths)if(p.role===role){path.moveTo(...p.points[0]);for(const pt of p.points.slice(1))path.lineTo(...pt);}
  const rgb=[1,3,5].map(i=>parseInt(ink.color_srgb.slice(i,i+2),16)/255);
  device.strokePath(path,stroke,transform,mupdf.ColorSpace.DeviceRGB,rgb,1);path.destroy();
 }
 device.close();device.destroy();stroke.destroy();
 const png=pixmap.asPNG(),hash=createHash('sha256').update(png).digest('hex'),name=`${family.id}.${hash}.png`;
 await writeFile(resolve(out,name),png);manifest[family.id]='/patterns/thumbnails/'+name;
 assets.push(`(${JSON.stringify(name)}, include_bytes!(concat!(env!("OUT_DIR"), "/pattern-thumbnails/${name}")))`);
 console.log(`${family.id}: ${png.length} bytes`);
 pixmap.destroy();
}
await writeFile(resolve(out,'manifest.js'),'export const thumbnails='+JSON.stringify(manifest)+';\n');
await writeFile(resolve(out,'assets.rs'),'// Generated by tools/build-pattern-thumbnails.mjs.\n'+
 'pub const MANIFEST: &str = include_str!(concat!(env!("OUT_DIR"), "/pattern-thumbnails/manifest.js"));\n'+
 'pub const IMAGES: &[(&str, &[u8])] = &[\n'+assets.join(',\n')+'\n];\n');
console.log(`Built ${families.length} pattern thumbnails in ${out}`);
