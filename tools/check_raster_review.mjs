import { chromium } from '../controller/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1400,height:950}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(process.argv[2] || 'http://127.0.0.1:11088/build/raster-review-northwest/');
await page.waitForSelector('body[data-ready="true"]');
const metadata=await page.evaluate(async()=>await (await fetch('review.json')).json());
assert.ok((await page.locator('#score').innerText()).includes(`${(metadata.ratio*100).toFixed(4)}%`));
if(metadata.sampling)assert.match(await page.locator('#sampling-note').innerText(),/864 dpi.*4×4/);
await page.selectOption('#preset','1');
assert.equal(await page.locator('body').getAttribute('data-zoom'),'3');
await page.click('[data-mode="blink"]');
const frame=await page.locator('body').getAttribute('data-frame');
await page.waitForFunction(previous=>document.body.dataset.frame!==previous,frame);
await page.click('#pause');
const frozen=await page.locator('body').getAttribute('data-frame');
await page.waitForTimeout(750);
assert.equal(await page.locator('body').getAttribute('data-frame'),frozen);
await page.click('#flip');assert.notEqual(await page.locator('body').getAttribute('data-frame'),frozen);
await page.click('[data-mode="diff"]');
assert.match(await page.locator('#caption-a').innerText(),/Magenta/);
await page.click('#share');const url=await page.locator('#share-link').inputValue();assert.match(url,/#mode=diff/);
await page.reload();await page.waitForSelector('body[data-ready="true"]');assert.equal(await page.locator('body').getAttribute('data-mode'),'diff');
await page.click('[data-mode="side"]');await page.selectOption('#preset','1');
await page.screenshot({path:'build/raster-review-browser.png',fullPage:true});
const rect=await page.locator('#a').boundingBox();await page.mouse.move(rect.x+rect.width/2,rect.y+rect.height/2);
assert.match(await page.locator('#cursor').innerText(),/PDF \[/);
await page.mouse.down();await page.mouse.move(rect.x+rect.width/2+70,rect.y+rect.height/2+30);await page.mouse.up();
await page.mouse.wheel(0,-100);await page.waitForTimeout(100);
assert.ok(Number(await page.locator('body').getAttribute('data-zoom'))>3);
assert.deepEqual(errors,[]);
await browser.close();console.log('PASS raster review: images, linked views, zoom/pan, blinking/pause, difference, shared view, RGB probe; no browser errors');
