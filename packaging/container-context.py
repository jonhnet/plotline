#!/usr/bin/env python3
"""Refresh the container's public-source allowlist after adding runtime files.

Run after staging new files. Exact paths also exclude ignored historical code,
credentials, artwork and live documents in an existing development checkout.
"""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
PREFIXES = ('src/', 'cartographer/', 'contracts/', 'controller/src/',
            'controller/web/', 'controller/layouts/', 'controller/profiles/',
            'controller/models/', 'controller/samples/',
            'patterns/', 'mazes/', 'shared/', 'native/', 'styles/', 'tools/',
            'raster_lab/', 'packaging/')
FILES = {'.dockerignore', 'Dockerfile', 'LICENSE', 'THIRD_PARTY.md', 'SOURCE_REVISION', 'Cargo.toml', 'Cargo.lock',
         'package.json', 'package-lock.json', 'controller/Cargo.toml',
         'controller/Cargo.lock', 'controller/build.rs',
         'controller/retention-policy.json', 'controller/scripts/retention.py',
         'controller/scripts/render-page.py'}


def main():
    files = subprocess.check_output(['git', 'ls-files', '-z'], cwd=ROOT).decode().split('\0')
    paths = set()
    for name in files:
        if name and (name in FILES or name.startswith(PREFIXES) or name.startswith('requirements-')):
            paths.add(name)
            paths.update(str(p) + '/' for p in Path(name).parents if str(p) != '.')
    content = '# Generated by python3 packaging/container-context.py after git add.\n'
    content += '# Deny everything except these public source paths. No state, keys or host builds.\n**\n'
    # Reopening a parent also reopens its descendants in Docker's matcher.
    # Immediately close those descendants again, then admit individual files.
    content += ''.join('!' + path + '\n' + (path + '**\n' if path.endswith('/') else '')
                       for path in sorted(paths))
    (ROOT / '.dockerignore').write_text(content)


if __name__ == '__main__':
    main()
